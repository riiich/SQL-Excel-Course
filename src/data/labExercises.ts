export function getLabExercises(lesson: Lesson): Exercise[] {
  const warmup = warmups[lesson.id]
  const extension = extensions[lesson.id]
  if (!warmup || !extension) return [lesson.exercise]
  return [
    { ...warmup, setupSql: lesson.exercise.setupSql },
    lesson.exercise,
    { ...extension, setupSql: lesson.exercise.setupSql },
  ]
}

export function exerciseProgressKey(lessonId: string, exerciseIndex: number) {
  return `${lessonId}:${exerciseIndex}`
}
